import type { User, Message, CollaborativeDoc, WebRtcTelemetrySample } from "./types.js";

type RealtimeEventType =
  | "connection:ack"
  | "presence:update"
  | "chat:message"
  | "chat:error"
  | "chat:sent"
  | "chat:delivered"
  | "chat:status"
  | "chat:read"
  | "chat:typing"
  | "chat:edit"
  | "chat:disappearing"
  | "chat:delete"
  | "chat:pin"
  | "chat:reaction"
  | "chat:poll_vote"
  | "chat:clear"
  | "call:invite"
  | "call:ringing"
  | "call:unavailable"
  | "call:ready"
  | "call:accept"
  | "call:decline"
  | "call:hangup"
  | "call:chat"
  | "call:add-participant"
  | "call:add-participant:error"
  | "call:participant-invited"
  | "call:participant-declined"
  | "call:participants"
  | "call:participant-left"
  | "webrtc:signal"
  | "whiteboard:stroke"
  | "whiteboard:clear"
  | "collab:notes"
  | "collab:task"
  | "telemetry:estimate";

type EventHandler = (payload: any) => void;

class RealtimeClient {
  private ws: WebSocket | null = null;
  private channel: BroadcastChannel | null = null;
  private listeners = new Map<string, Set<EventHandler>>();
  private reconnectTimer: number | null = null;
  private isConnected = false;
  private currentUser: User | null = null;
  private socketUserId: string | null = null;
  private connectionWaiters = new Set<{
    resolve: () => void;
    reject: (error: Error) => void;
    timer: number;
  }>();
  private queuedPayloads: string[] = [];
  private tabId = Math.random().toString(36).slice(2, 9);
  private seenEventIds = new Set<string>();

  constructor() {
    if (typeof window !== "undefined" && "BroadcastChannel" in window) {
      try {
        this.channel = new BroadcastChannel("connect_sphere_realtime_bus");
        this.channel.onmessage = (event) => {
          if (event.data && typeof event.data === "object") {
            // Ignore events generated by the current tab
            if (event.data.tabId === this.tabId) return;
            if (event.data.eventId) {
              if (this.seenEventIds.has(event.data.eventId)) return;
              this.seenEventIds.add(event.data.eventId);
              this.pruneSeenEvents();
            }
            const payload = event.data.payload && typeof event.data.payload === "object"
              ? { ...event.data.payload, conversationId: event.data.payload.conversationId ?? event.data.conversationId }
              : (event.data.payload ?? event.data);
            this.emit(event.data.type, payload);
          }
        };
      } catch (err) {
        console.warn("BroadcastChannel initialization skipped:", err);
      }
    }
  }

  private pruneSeenEvents() {
    if (this.seenEventIds.size > 500) {
      const arr = Array.from(this.seenEventIds);
      this.seenEventIds = new Set(arr.slice(arr.length - 250));
    }
  }

  public connect(user?: User) {
    if (user) {
      const identityChanged = this.currentUser !== null && this.currentUser.id !== user.id;
      this.currentUser = user;
      if (identityChanged) {
        this.queuedPayloads = [];
        this.closeSocket(false);
      }
    }
    if (typeof window === "undefined") return;

    if (
      this.ws &&
      this.socketUserId === (this.currentUser?.id ?? null) &&
      (this.ws.readyState === WebSocket.OPEN || this.ws.readyState === WebSocket.CONNECTING)
    ) {
      return;
    }

    try {
      const protocol = window.location.protocol === "https:" ? "wss:" : "ws:";
      const host = window.location.host;
      const wsUrl = `${protocol}//${host}/ws`;

      const socket = new WebSocket(wsUrl);
      this.ws = socket;
      this.socketUserId = this.currentUser?.id ?? null;

      socket.onopen = () => {
        if (this.ws !== socket) return;
        this.isConnected = true;
        this.resolveConnectionWaiters();
        if (this.reconnectTimer) {
          clearTimeout(this.reconnectTimer);
          this.reconnectTimer = null;
        }

        // Identify authenticated or current user
        if (this.currentUser) {
          this.send("identify", {
            userId: this.currentUser.id,
            username: this.currentUser.username,
            displayName: this.currentUser.displayName,
            avatar: this.currentUser.avatar,
            phone: this.currentUser.phone,
          });
        }

        // Flush offline queued payloads
        while (this.queuedPayloads.length > 0) {
          const item = this.queuedPayloads.shift();
          if (item && socket.readyState === WebSocket.OPEN) {
            socket.send(item);
          }
        }
      };

      socket.onmessage = (event) => {
        if (this.ws !== socket) return;
        try {
          const data = JSON.parse(event.data);
          if (data && data.type) {
            if (data.eventId) {
              if (this.seenEventIds.has(data.eventId)) return;
              this.seenEventIds.add(data.eventId);
              this.pruneSeenEvents();
            }
            const payload = data.payload && typeof data.payload === "object"
              ? { ...data.payload, conversationId: data.payload.conversationId ?? data.conversationId }
              : (data.payload ?? data);
            this.emit(data.type, payload);
          }
        } catch (err) {
          console.warn("Failed to parse incoming realtime message:", err);
        }
      };

      socket.onclose = () => {
        if (this.ws !== socket) return;
        this.ws = null;
        this.socketUserId = null;
        this.isConnected = false;
        this.rejectConnectionWaiters(new Error("Realtime connection closed before the call could be started."));
        this.scheduleReconnect();
      };

      socket.onerror = () => {
        if (this.ws !== socket) return;
        this.isConnected = false;
        this.rejectConnectionWaiters(new Error("Realtime connection failed. Check your network and sign in again."));
      };
    } catch {
      this.scheduleReconnect();
    }
  }

  public waitUntilConnected(timeoutMs = 10_000): Promise<void> {
    if (this.ws?.readyState === WebSocket.OPEN && this.isConnected) return Promise.resolve();
    this.connect();
    return new Promise((resolve, reject) => {
      const waiter = {
        resolve: () => {
          window.clearTimeout(waiter.timer);
          this.connectionWaiters.delete(waiter);
          resolve();
        },
        reject: (error: Error) => {
          window.clearTimeout(waiter.timer);
          this.connectionWaiters.delete(waiter);
          reject(error);
        },
        timer: window.setTimeout(() => {
          waiter.reject(new Error("Realtime server did not connect. Check the app server and try again."));
        }, timeoutMs),
      };
      this.connectionWaiters.add(waiter);
    });
  }

  private resolveConnectionWaiters() {
    for (const waiter of this.connectionWaiters) waiter.resolve();
  }

  private rejectConnectionWaiters(error: Error) {
    for (const waiter of this.connectionWaiters) waiter.reject(error);
  }

  public disconnect() {
    if (this.reconnectTimer !== null) {
      clearTimeout(this.reconnectTimer);
      this.reconnectTimer = null;
    }
    this.queuedPayloads = [];
    this.currentUser = null;
    this.isConnected = false;
    this.rejectConnectionWaiters(new Error("Realtime connection was closed."));
    this.closeSocket(true);
  }

  private closeSocket(detachHandlers: boolean) {
    const socket = this.ws;
    this.ws = null;
    this.socketUserId = null;
    if (!socket) return;
    if (detachHandlers) {
      socket.onopen = null;
      socket.onmessage = null;
      socket.onclose = null;
      socket.onerror = null;
    }
    if (socket.readyState === WebSocket.OPEN || socket.readyState === WebSocket.CONNECTING) {
      socket.close(1000, "Session changed");
    }
  }

  private scheduleReconnect() {
    if (this.reconnectTimer) return;
    this.reconnectTimer = window.setTimeout(() => {
      this.reconnectTimer = null;
      this.connect();
    }, 3000);
  }

  public subscribe(type: RealtimeEventType, handler: EventHandler): () => void {
    if (!this.listeners.has(type)) {
      this.listeners.set(type, new Set());
    }
    this.listeners.get(type)!.add(handler);

    return () => {
      this.listeners.get(type)?.delete(handler);
    };
  }

  private emit(type: string, payload: any) {
    const handlers = this.listeners.get(type);
    if (handlers) {
      for (const handler of handlers) {
        try {
          handler(payload);
        } catch (err) {
          console.error(`Error in realtime listener for ${type}:`, err);
        }
      }
    }
  }

  public send(
    type: RealtimeEventType | string,
    payload: any,
    conversationId?: string,
    callId?: string,
    queueWhenDisconnected = true,
  ): boolean {
    const eventId = `${type}_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
    this.seenEventIds.add(eventId);
    this.pruneSeenEvents();

    const message = {
      type,
      payload,
      senderId: this.currentUser?.id,
      conversationId,
      callId,
      eventId,
      tabId: this.tabId,
      timestamp: Date.now(),
    };

    if (
      !queueWhenDisconnected &&
      (!this.ws || this.ws.readyState !== WebSocket.OPEN || !this.isConnected)
    ) {
      return false;
    }

    // 1. Broadcast locally across multiple tabs on the same machine
    if (this.channel) {
      try {
        this.channel.postMessage(message);
      } catch {}
    }

    // 2. Dispatch via WebSocket to backend server
    const raw = JSON.stringify(message);
    if (this.ws && this.ws.readyState === WebSocket.OPEN) {
      try {
        this.ws.send(raw);
        return true;
      } catch {
        if (queueWhenDisconnected) this.queuedPayloads.push(raw);
        return false;
      }
    } else {
      if (queueWhenDisconnected) this.queuedPayloads.push(raw);
      return false;
    }
  }

  // --- Realtime API methods ---

  public sendMessage(conversationId: string, message: Message) {
    this.send("chat:message", message, conversationId);
  }

  public sendTyping(conversationId: string, isTyping: boolean) {
    this.send("chat:typing", { isTyping, user: this.currentUser, conversationId }, conversationId);
  }

  public sendStatus(messageId: string, conversationId: string, status: "delivered" | "read") {
    this.send("chat:status", { messageId, conversationId, status }, conversationId);
  }

  public sendReadReceipts(conversationId: string, messageIds: string[]) {
    for (let index = 0; index < messageIds.length; index += 100) {
      this.send("chat:read", { messageIds: messageIds.slice(index, index + 100) }, conversationId);
    }
  }

  public sendCallInvite(
    callId: string,
    peerName: string,
    isVideo: boolean,
    peerAvatar?: string,
    targetUserId?: string,
    targetPhone?: string
  ): boolean {
    return this.send(
      "call:invite",
      { callId, peerName, peerAvatar, isVideo, fromUser: this.currentUser, targetUserId, targetPhone },
      undefined,
      callId,
      false,
    );
  }

  public sendCallAccept(callId: string): boolean {
    return this.send("call:accept", { callId, byUser: this.currentUser }, undefined, callId, false);
  }

  public sendCallReady(callId: string): boolean {
    return this.send("call:ready", { callId }, undefined, callId, false);
  }

  public sendCallDecline(callId: string): boolean {
    return this.send("call:decline", { callId, byUser: this.currentUser }, undefined, callId, false);
  }

  public sendCallHangup(callId: string): boolean {
    return this.send("call:hangup", { callId, byUser: this.currentUser }, undefined, callId, false);
  }

  public sendCallChat(callId: string, id: string, text: string): boolean {
    return this.send("call:chat", { id, text }, undefined, callId, false);
  }

  public sendCallAddParticipant(
    callId: string,
    contact: { targetUserId?: string; targetPhone?: string; isVideo: boolean },
  ): boolean {
    return this.send("call:add-participant", contact, undefined, callId, false);
  }

  public sendWebrtcSignal(
    callId: string,
    toUserId: string,
    signal: RTCSessionDescriptionInit | { candidate: RTCIceCandidateInit },
  ): boolean {
    return this.send("webrtc:signal", { callId, toUserId, signal }, undefined, callId, false);
  }

  public sendWhiteboardStroke(stroke: {
    points: { x: number; y: number }[];
    color: string;
    width: number;
    tool: string;
    normalized?: boolean;
  }, callId?: string) {
    this.send("whiteboard:stroke", stroke, undefined, callId, !callId);
  }

  public sendWhiteboardClear(callId?: string) {
    this.send("whiteboard:clear", {}, undefined, callId, !callId);
  }

  public sendCollabNotes(content: string, callId?: string) {
    this.send("collab:notes", { content }, undefined, callId, !callId);
  }

  public sendCollabTask(taskId: string, completed: boolean, text?: string) {
    this.send("collab:task", { taskId, completed, ...(text !== undefined ? { text } : {}) });
  }

  public sendTelemetrySample(sample: WebRtcTelemetrySample) {
    this.send("telemetry:sample", { sample });
  }
}

export const realtime = new RealtimeClient();
